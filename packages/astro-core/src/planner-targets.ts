export function localizedPlannerName(
  name: string,
  locale = "fr",
  labels: PlannerNameLabels = plannerNameLabels,
): string {
  if (locale === "fr") return name;
  // A locale without its own name reads the English one, never the French
  // key (absent = English, the content rule of the locale registry).
  return (
    labels?.[name]?.[locale] ||
    plannerNamesMore[name]?.[locale] ||
    labels?.[name]?.en ||
    name
  );
}

