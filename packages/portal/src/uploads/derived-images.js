/**
 * The files derived from a capture's original, written with `sharp` beside
 * it, never over it — the original is never modified:
 *
 * - the **thumbnail** (`thumbnail.webp`): a raster image oriented by its
 *   EXIF, reduced to `THUMBNAIL_LONG_SIDE` on its long side, WebP, without
 *   any metadata; a FITS file whose pixels the sky check's reader can give
 *   (`sky-check/decode.js`) gets one too, stretched for the eye; any other
 *   file (XISF, a camera's raw file, a document) gets none, and the page
 *   draws its placeholder;
 * - the **shared copy** (`shared.jpg`): the only file the public gallery and
 *   a private gallery serve. JPEG, 8 bits, sRGB, oriented, its long side at
 *   `SHARED_COPY_LONG_SIDE` (4096 px) at most and never enlarged, and
 *   **without EXIF, XMP or IPTC** — no GPS, no place, no camera serial, no
 *   comment: `sharp` writes no metadata unless asked, and nothing here asks.
 *   Only a raster image (`rasterImageTypeOf`: JPEG, PNG, WebP, AVIF, TIFF)
 *   that is not a camera's raw file can have one; any other file is
 *   `not_showable`.
 *
 * `sharp` is loaded by `await import` when an image is written, never when
 * this module loads: the module stays out of the static import graph of
 * `server.mjs`, which loads nothing but `next` and `pg`.
 *
 * The original is read and the derived files are written through the
 * capture store (`capture-store.js`, the service's unless `captureStore` is
 * given): `sharp` and the FITS reader get a path on this machine
 * (`withLocalFile`, the file itself on the disk store), a derived file is
 * written to a temporary path and published by the store (`put`). A caller
 * that already holds the original on this machine passes its path as
 * `original`, so a store elsewhere does not fetch it again.
 */

import { extname } from "node:path";
import { captureStore } from "./capture-store.js";
import { rasterImageTypeOf, readFileHead } from "./media-type.js";
import { decodeFits } from "../sky-check/decode.js";
import { readImageMetadata } from "../sky-check/image-metadata.js";
import {
  FITS_BLOCK_BYTES,
  FITS_MAX_HEADER_BLOCKS,
  fitsNumber,
  isFitsHead,
  parseFitsHeader,
} from "../sky-check/fits-header.js";

/** The long side of a thumbnail: the opened capture's image, sharp at 2×. */
export const THUMBNAIL_LONG_SIDE = 768;

/** The long side of the shared copy at most. */
export const SHARED_COPY_LONG_SIDE = 4096;

/**
 * The JPEG quality of the shared copy and the WebP quality of a thumbnail.
 * 92 for the shared copy (the copy the opened capture is drawn with), chroma
 * not subsampled (4:4:4). A copy written before is not rewritten: it is
 * regenerated by removing its `shared.jpg` (the next view writes it again).
 */
export const SHARED_COPY_QUALITY = 92;
export const THUMBNAIL_QUALITY = 80;

/** Pixels of a source decoded at most (a 16-bit mosaic of 250 Mpx passes). */
const MAX_INPUT_PIXELS = 268_402_689;

/** Time one derived file may take, seconds (generous for a small CPU). */
const TIME_LIMIT_SECONDS = 60;

const SOURCE_OPTIONS = Object.freeze({
  limitInputPixels: MAX_INPUT_PIXELS,
  sequentialRead: true,
  failOn: "error",
  pages: 1,
});

export class DerivedImageError extends Error {
  constructor(code, message) {
    super(message || code);
    this.name = "DerivedImageError";
    this.code = code;
  }
}

async function loadSharp() {
  try {
    return (await import("sharp")).default;
  } catch {
    throw new DerivedImageError("sharp_unavailable", "sharp is not installed");
  }
}

const exists = async (files, reference) => Boolean(await files.stat(reference));

/** The original of a reference's capture, on this machine, for `use(path)`. */
const withOriginal = (files, { tenantId, sha256 }, original, use) =>
  original
    ? use(original)
    : files.withLocalFile({ tenantId, sha256, file: "original" }, use);

// ——— A FITS file's grey plane, made visible ———

/** The midtones transfer function (PixInsight's `MTF`). */
function midtones(m, x) {
  if (x <= 0) return 0;
  if (x >= 1) return 1;
  return ((m - 1) * x) / ((2 * m - 1) * x - m);
}

/**
 * Eight bits from a linear plane: the shadows clipped under the median less
 * 2.8 deviations, then the midtones set so that the median reads 0.25 — the
 * automatic stretch every astronomy viewer applies to a linear frame.
 */
export function stretchToEightBits({ pixels, saturation }) {
  const count = pixels.length;
  const out = Buffer.alloc(count);
  if (!count || !(saturation > 0)) return out;
  const step = Math.max(1, Math.floor(count / 200_000));
  const sample = [];
  for (let index = 0; index < count; index += step)
    sample.push(Math.min(1, Math.max(0, pixels[index] / saturation)));
  sample.sort((a, b) => a - b);
  const median = sample[Math.floor(sample.length / 2)];
  const deviations = sample
    .map((value) => Math.abs(value - median))
    .sort((a, b) => a - b);
  const mad = 1.4826 * deviations[Math.floor(deviations.length / 2)];
  const shadows = Math.max(0, median - 2.8 * mad);
  const span = Math.max(1e-9, 1 - shadows);
  const centre = (median - shadows) / span;
  const target = 0.25;
  const balance =
    centre > 0 && centre < 1
      ? (centre * (target - 1)) / (2 * centre * target - target - centre)
      : 0.5;
  for (let index = 0; index < count; index += 1) {
    const x = (pixels[index] / saturation - shadows) / span;
    out[index] = Math.round(255 * midtones(balance, x));
  }
  return out;
}

async function fitsThumbnail(sharp, original, temporaryPath) {
  const head = await readFileHead(
    original,
    FITS_BLOCK_BYTES * FITS_MAX_HEADER_BLOCKS,
  );
  const header = parseFitsHeader(head);
  if (!header.ok) return false;
  const decoded = await decodeFits(original, header, {
    longSide: THUMBNAIL_LONG_SIDE,
    maxPixels: 120_000_000,
    deadline: performance.now() + TIME_LIMIT_SECONDS * 1000,
  });
  const { width, height } = decoded.frame;
  // FITS rows run from the bottom of the image up: shown the right way up.
  await sharp(stretchToEightBits(decoded.frame), {
    raw: { width, height, channels: 1 },
  })
    .flip()
    .webp({ quality: THUMBNAIL_QUALITY })
    .toFile(temporaryPath);
  return true;
}

/**
 * Writes the thumbnail of one capture of a space. Answers `{ written: true,
 * path }`, or `{ written: false }` for a file that has none (any other
 * format); throws `DerivedImageError` when a file that should have one
 * cannot be read.
 */
export async function writeThumbnail({
  tenantId,
  sha256,
  original: given = null,
  captureStore: files = captureStore(),
}) {
  const reference = { tenantId, sha256, file: "thumbnail" };
  const path = files.pathOf?.(reference) ?? null;
  return await withOriginal(files, reference, given, (original) =>
    thumbnailFrom({ files, reference, original, path }),
  );
}

async function thumbnailFrom({ files, reference, original, path }) {
  const head = await readFileHead(original);
  const raster = Boolean(rasterImageTypeOf(head));
  if (!raster && !isFitsHead(head)) return { written: false };
  const sharp = await loadSharp();
  let written = true;
  try {
    await files.put(reference, async (temporary) => {
      if (!raster) {
        written = await fitsThumbnail(sharp, original, temporary);
        if (!written) throw new DerivedImageError("unreadable");
        return;
      }
      await sharp(original, SOURCE_OPTIONS)
        .timeout({ seconds: TIME_LIMIT_SECONDS })
        .rotate()
        .resize({
          width: THUMBNAIL_LONG_SIDE,
          height: THUMBNAIL_LONG_SIDE,
          fit: "inside",
          withoutEnlargement: true,
        })
        .toColourspace("srgb")
        .webp({ quality: THUMBNAIL_QUALITY })
        .toFile(temporary);
    });
  } catch (error) {
    if (error instanceof DerivedImageError) throw error;
    throw new DerivedImageError("unreadable", String(error?.message || error));
  }
  return { written, path };
}

/**
 * The dimensions in pixels of one original of a space (each image of a
 * capture carries them), as shown: a raster image's, turned by its EXIF
 * orientation; a FITS file's `NAXIS1` × `NAXIS2`. `null` for any other file
 * or one that cannot be read. Reads the header only.
 */
export async function readImageDimensions({
  tenantId,
  sha256,
  original: given = null,
  captureStore: files = captureStore(),
}) {
  try {
    return await withOriginal(files, { tenantId, sha256 }, given, (original) =>
      dimensionsOf(original),
    );
  } catch {
    return null;
  }
}

async function dimensionsOf(original) {
  try {
    const head = await readFileHead(original);
    if (rasterImageTypeOf(head)) {
      const sharp = await loadSharp();
      const { width, height, orientation } = await sharp(
        original,
        SOURCE_OPTIONS,
      ).metadata();
      if (!Number.isSafeInteger(width) || !Number.isSafeInteger(height))
        return null;
      return Number(orientation) >= 5
        ? { width: height, height: width }
        : { width, height };
    }
    if (isFitsHead(head)) {
      const header = parseFitsHeader(
        await readFileHead(original, FITS_BLOCK_BYTES * FITS_MAX_HEADER_BLOCKS),
      );
      if (!header.ok) return null;
      const width = fitsNumber(header.cards, "NAXIS1");
      const height = fitsNumber(header.cards, "NAXIS2");
      return Number.isSafeInteger(width) && Number.isSafeInteger(height)
        ? { width, height }
        : null;
    }
  } catch {
    return null;
  }
  return null;
}

/** Whether a capture of a space has its thumbnail. */
export const hasThumbnail = (
  tenantId,
  sha256,
  { captureStore: files = captureStore() } = {},
) => exists(files, { tenantId, sha256, file: "thumbnail" });

/**
 * The raster type of an original a gallery can show, or `null`: a JPEG,
 * PNG, WebP, AVIF or TIFF image, never a camera's raw file (a CR2, NEF,
 * ARW or DNG is built like a TIFF; its own pixels are not an image to
 * publish). `originalName` gives the extension the raw detection reads.
 */
async function showableTypeOf(files, reference, originalName) {
  const head = await files.head(reference);
  if (!head) throw new DerivedImageError("unreadable", "original missing");
  const type = rasterImageTypeOf(head);
  if (type !== "image/tiff") return type;
  const found = await files.stat(reference);
  if (!found) throw new DerivedImageError("unreadable", "original missing");
  const { size } = found;
  const metadata = await readImageMetadata(
    {
      size,
      async readAt(offset, length) {
        const start = Math.max(0, offset);
        const bounded = Math.max(0, Math.min(length, size - start));
        if (!bounded) return Buffer.alloc(0);
        const read = await files.read(reference, {
          start,
          end: start + bounded - 1,
        });
        if (!read) return Buffer.alloc(0);
        const chunks = [];
        for await (const chunk of read.stream) chunks.push(chunk);
        return Buffer.concat(chunks).subarray(0, bounded);
      },
    },
    {
      type,
      extension: extname(String(originalName || "")).slice(1),
    },
  );
  return metadata.raw ? null : type;
}

/**
 * Whether a capture's original can have a shared copy: a raster image a
 * gallery can show (never a FITS, an XISF, a camera's raw file).
 */
export async function isShowable(
  tenantId,
  sha256,
  { originalName, captureStore: files = captureStore() } = {},
) {
  try {
    return Boolean(
      await showableTypeOf(
        files,
        { tenantId, sha256, file: "original" },
        originalName,
      ),
    );
  } catch {
    return false;
  }
}

/**
 * The shared copy of one capture of a space, written at its first need (the
 * capture made public, or first shown in a private gallery) and kept
 * afterwards. Answers `{ path, created }`; throws `DerivedImageError` with
 * `not_showable` for a file that is not a raster image, `shared_copy_failed`
 * when the image cannot be read or written.
 */
export async function ensureSharedCopy({
  tenantId,
  sha256,
  originalName,
  captureStore: files = captureStore(),
}) {
  const reference = { tenantId, sha256, file: "shared" };
  const path = files.pathOf?.(reference) ?? null;
  if (await exists(files, reference)) return { path, created: false };
  const source = { tenantId, sha256, file: "original" };
  let type;
  try {
    type = await showableTypeOf(files, source, originalName);
  } catch {
    throw new DerivedImageError("shared_copy_failed", "original unreadable");
  }
  if (!type)
    throw new DerivedImageError(
      "not_showable",
      "Only an image can be shown in a gallery.",
    );
  const sharp = await loadSharp();
  try {
    await files.withLocalFile(source, (original) =>
      files.put(reference, (temporary) =>
        sharp(original, SOURCE_OPTIONS)
          .timeout({ seconds: TIME_LIMIT_SECONDS })
          .rotate()
          .resize({
            width: SHARED_COPY_LONG_SIDE,
            height: SHARED_COPY_LONG_SIDE,
            fit: "inside",
            withoutEnlargement: true,
          })
          .flatten({ background: "#000000" })
          .toColourspace("srgb")
          .jpeg({
            quality: SHARED_COPY_QUALITY,
            mozjpeg: true,
            chromaSubsampling: "4:4:4",
          })
          .toFile(temporary),
      ),
    );
  } catch (error) {
    throw new DerivedImageError(
      "shared_copy_failed",
      String(error?.message || error),
    );
  }
  return { path, created: true };
}
