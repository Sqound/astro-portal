const literal = (value) => `'${String(value).replaceAll("'", "''")}'`;

const patchOf = (row) =>
  JSON.stringify({
    ...(row.maker ? { maker: row.maker } : {}),
    ...(row.kind ? { kind: row.kind } : {}),
  });

/**
 * The statements of migration 108 in `dialect`: one update per row, the
 * row's `planner_json` merged with `{ maker, kind }` (PostgreSQL's `jsonb`
 * `||`, SQLite's `json_patch`), so that running them twice changes nothing.
 * The migration runner cuts the text at every « ; »: no value holds one.
 */
export function defaultEquipmentMakerKindSql(dialect) {
  return DEFAULT_EQUIPMENT_MAKER_KIND.map((row) => {
    const patch = literal(patchOf(row));
    const merged =
      dialect === "postgres"
        ? `(planner_json::jsonb || ${patch}::jsonb)::text`
        : `json_patch(planner_json, ${patch})`;
    return `UPDATE equipment SET planner_json = ${merged} WHERE tenant_id = ${literal(PLATFORM_ORGANIZATION_ID)} AND scope = 'default' AND equipment_type = ${literal(row.type)} AND id = ${literal(row.id)};`;
  }).join("\n");
}
