// Attaching existing nights.
for (const [locale, words] of Object.entries(NIGHTS_COPY))
  Object.assign(MULTI_NIGHT_COPY[locale], words);

/** The words of `locale` (English for a language the web does not speak). */
export const multiNightCopy = (locale) =>
  copyFor(MULTI_NIGHT_COPY, locale, "MULTI_NIGHT_COPY");

/** `{name}` → `values.name`, every occurrence. */
export function fill(template, values = {}) {
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value ?? "")),
    String(template ?? ""),
  );
}

/** The template `key` of `locale`, filled. A plural takes `values.count`. */
export function say(locale, key, values = {}) {
  const entry = multiNightCopy(locale)[key];
  if (entry && typeof entry === "object" && "other" in entry) {
    const count = Number(values.count ?? 0);
    return fill(pluralTemplate(entry, count), values);
  }
  return fill(entry, values);
}

/** One of the choices of a select (`outcome`, `forecast`, `noWindow`…). */
export function choose(locale, key, choice, values = {}) {
  const entry = multiNightCopy(locale)[key] || {};
  return fill(entry[choice] ?? entry.other ?? "", values);
}
