// The words of the multi-night plans on the web. "Projet" is the internal name
// and is never shown: the observer reads "plan multi-nuits", "les nuits" of a
// multi-night plan and "plan d’une nuit" where the two kinds are told apart.
//
// A template names its values `{name}`; a plural is a function of its count.

const plural = (one, other, zero = null) => ({ one, other, zero });

// Russian counts in three forms (CLDR `ru`: 1, 21 → one; 2–4, 22–24 → few;
// 0, 5–20, 25–30 → many), each written with `{count}`; `zero` is the
// sentence of nothing. `other` (fractions) takes the form of `many`.
const pluralRu = ({ one, few, many, zero = null }) => ({
  one,
  few,
  many,
  other: many,
  zero,
});

/** The template of a plural entry for `count`. */
function pluralTemplate(entry, count) {
  if (count === 0 && entry.zero !== null) return entry.zero;
  if ("few" in entry) {
    return entry[new Intl.PluralRules("ru").select(count)] ?? entry.other;
  }
  return count === 1 ? entry.one : entry.other;
}

